# Evaluation prompt templates
# ---------------------------------------------------------------------------
USER_FRUSTRATION_TEMPLATE = """You are evaluating a travel assistant chatbot interaction.

User query: {query}
Assistant response: {response}

Determine whether the user would likely feel frustrated after receiving this response.

A user is FRUSTRATED if:
- The assistant could not fulfil the user's primary request (e.g. booking, pricing)
- The response is overly vague, incomplete, or unhelpful
- The assistant gave a generic answer when a specific one was needed
- The user asked for something actionable but got a wall of text with no clear next step

A user is NOT FRUSTRATED if:
- The assistant directly and accurately answered the question
- The assistant clearly explained what it cannot do AND provided helpful alternatives
- The response is specific, relevant, and useful

Respond with a JSON object with exactly these fields:
{{
  "label": "frustrated" or "not frustrated",
  "score": 1.0 if frustrated, 0.0 if not frustrated,
  "explanation": "one sentence explaining your judgment"
}}"""

TOOL_USAGE_TEMPLATE = """You are evaluating whether an AI travel assistant used the correct tools.

Available tools:
- duckduckgo_search: for general travel information (attractions, hotels, visas, etc.)
- get_current_weather: ONLY for current weather or temperature conditions
- (no tool): for booking or flight pricing — agent should decline gracefully

User query: {query}
Expected tool: {expected_tool}
Assistant response: {response}

Clues the tool was used correctly:
- Weather queries answered with specific temperatures → get_current_weather called
- Travel info answered with specific current details → duckduckgo_search called
- Booking queries declined gracefully with alternatives → no tool needed

Clues the tool was used INCORRECTLY:
- Weather query answered without temperature data
- Travel info answered with generic LLM knowledge (no specific current facts)
- Agent tried to book or price something (hallucination)

Respond with a JSON object with exactly these fields:
{{
  "label": "correct" or "incorrect",
  "score": 1.0 if correct, 0.0 if incorrect,
  "explanation": "one sentence explaining your judgment"
}}"""


# ---------------------------------------------------------------------------
# LangChain span input/output parsing
# ---------------------------------------------------------------------------
def _extract_query_from_span_input(raw_input) -> str:
    """Extract the user's plain-text query from a LangChain span's input.value.

    LangChain/LangGraph serialises HumanMessage in several formats:

      Format A — LangChain ≥0.3 / OpenInference:
        {"messages": [{"type": "human", "data": {"content": "query here"}}]}

      Format B — plain dict:
        {"messages": [{"type": "human", "content": "query here"}]}

      Format C — LangChain constructor serialisation:
        {"messages": [[{"lc": 1, "type": "constructor",
                        "id": [..., "HumanMessage"],
                        "kwargs": {"content": "query here"}}]]}

    Returns the first non-AI message content found, or empty string.
    """
    if not raw_input:
        return ""
    if isinstance(raw_input, str) and not raw_input.strip().startswith("{"):
        return raw_input.strip()
    try:
        data = json.loads(raw_input) if isinstance(raw_input, str) else raw_input
    except (json.JSONDecodeError, TypeError):
        return str(raw_input)

    messages = data.get("messages", []) if isinstance(data, dict) else []
    ai_roles = {"ai", "assistant", "aimessage", "function", "tool"}

    def _content(msg: dict) -> str:
        c = (msg.get("data") or {}).get("content", "")
        if not c:
            c = msg.get("content", "")
        if not c:
            c = (msg.get("kwargs") or {}).get("content", "")
        return c if isinstance(c, str) else ""

    for item in messages:
        if isinstance(item, list):
            item = item[0] if item else {}
        if not isinstance(item, dict):
            continue
        role = (item.get("type", "") or item.get("role", "")).lower()
        if role in ai_roles:
            continue
        if role == "constructor":
            if not any("human" in str(i).lower() for i in item.get("id", [])):
                continue
        content = _content(item)
        if content.strip():
            return content.strip()

    return str(raw_input)


# ---------------------------------------------------------------------------
# Phoenix client helpers
# ---------------------------------------------------------------------------
def get_phoenix_spans() -> pd.DataFrame:
    """Export all spans for the project as a DataFrame via px.Client().

    Uses the Phoenix Python client (get_spans_dataframe) which
    returns a DataFrame whose index is the OTel span_id. This is the
    correct ID to use with px.log_evaluations() and SpanEvaluations.

    Returns an empty DataFrame if Phoenix is unreachable or unavailable.
    """
    if not _PHOENIX_AVAILABLE or px is None:
        return pd.DataFrame()
    try:
        phoenix_client = px.Client(endpoint=PHOENIX_BASE_URL)
        df = phoenix_client.get_spans_dataframe(project_name=PHOENIX_PROJECT)
        if df is not None and not df.empty:
            print(f"  Exported {len(df)} spans from Phoenix")
            return df
        print("  No spans found in Phoenix — make sure run_queries.py was run first")
        return pd.DataFrame()
    except Exception as exc:
        print(f"  [warn] Could not export spans from Phoenix: {exc}")
        return pd.DataFrame()


def build_span_query_map(spans_df: pd.DataFrame) -> dict[str, str]:
    """Build {query_prefix → span_id} from Phoenix spans DataFrame.

    Filters to root spans (parent_id is NaN) and parses each span's
    input value to extract the user query. Root spans correspond to the
    top-level LangGraph invocations — one per user request.

    Phoenix ≥8 prefixes all OpenInference attributes with "attributes."
    so the column is "attributes.input.value" rather than "input.value".
    We try both to support multiple server versions.

    The resulting map is used to attach evaluation results to the correct
    span when calling px.Client().log_evaluations().
    """
    if spans_df.empty:
        return {}

    # Normalise index — some Phoenix versions put span_id as a column
    if "context.span_id" in spans_df.columns and spans_df.index.name != "context.span_id":
        spans_df = spans_df.set_index("context.span_id")

    # Root spans have no parent
    if "parent_id" in spans_df.columns:
        root_spans = spans_df[spans_df["parent_id"].isna()]
    else:
        root_spans = spans_df

    # Phoenix 16.x uses "attributes.input.value"; older versions used "input.value"
    input_col = (
        "attributes.input.value"
        if "attributes.input.value" in spans_df.columns
        else "input.value"
    )

    mapping: dict[str, str] = {}
    for span_id, row in root_spans.iterrows():
        raw_inp = row.get(input_col, "") or ""
        query = _extract_query_from_span_input(raw_inp)
        if query:
            mapping[query[:100]] = str(span_id)
        else:
            # Fallback: try attributes.output.value too (some root spans store
            # the messages in output rather than input depending on instrumentation)
            raw_out = row.get("attributes.output.value", "") or ""
            query = _extract_query_from_span_input(raw_out)
            if query:
                mapping[query[:100]] = str(span_id)

    return mapping


def log_evaluations_to_phoenix(results: list[dict]) -> None:
    """Upload LLM-judge results to Phoenix via the REST API.

    Phoenix 16.x uses POST /v1/span_annotations (JSON) rather than the
    Arrow-based /v1/evaluations endpoint from older clients.  We call it
    directly with requests so the Phoenix client version is irrelevant.

    Creates two annotation dimensions per span:
      - user_frustration       (label: frustrated / not frustrated, score 0-1)
      - tool_usage_correctness (label: correct / incorrect, score 0-1)

    These appear in the Phoenix Traces UI as named annotation columns.
    """
    import requests as _requests

    annotatable = [r for r in results if r.get("span_id")]
    if not annotatable:
        print("  [warn] No span IDs matched — annotation upload skipped")
        print("  [hint] Ensure run_queries.py ran with Phoenix up, then re-run this script")
        return

    # Build annotation objects per Phoenix 16.x schema:
    # label/score/explanation must be nested inside a "result" object.
    annotations = []
    for r in annotatable:
        annotations.append({
            "span_id": r["span_id"],
            "name": "user_frustration",
            "annotator_kind": "LLM",
            "result": {
                "label": r["frustration_label"],
                "score": float(r.get("frustration_score") or 0),
                "explanation": r["frustration_explanation"],
            },
        })
        annotations.append({
            "span_id": r["span_id"],
            "name": "tool_usage_correctness",
            "annotator_kind": "LLM",
            "result": {
                "label": r["tool_usage_label"],
                "score": float(r.get("tool_usage_score") or 0),
                "explanation": r["tool_usage_explanation"],
            },
        })

    try:
        resp = _requests.post(
            f"{PHOENIX_BASE_URL}/v1/span_annotations",
            json={"data": annotations},
            headers={"Content-Type": "application/json"},
            timeout=30,
        )
        resp.raise_for_status()
        print(f"  Uploaded {len(annotations)} annotations for {len(annotatable)} spans ✓")
        print("  Phoenix Traces UI → open any trace → Annotations tab")
    except Exception as exc:
        print(f"  [warn] Annotation upload failed: {exc}")


def create_phoenix_dataset(results: list[dict]) -> None:
    """Create a reusable evaluation dataset in Phoenix Datasets & Experiments.

    Uploads the 10 query/response/label rows as a named Phoenix dataset.
    Datasets can be used to run future evaluation iterations, compare
    models/prompts, and track quality over time — they appear in the
    Datasets & Experiments section of the Phoenix UI.

    Falls back to a CSV tip if the API is unavailable or the method
    signature differs from this Phoenix version.
    """
    if not _PHOENIX_AVAILABLE or px is None:
        return

    dataset_df = pd.DataFrame([
        {
            "input": r["message"],
            "output": r["response"],
            "group": r["group"],
            "expected_tool": r.get("expected_tool", ""),
            "frustration_label": r["frustration_label"],
            "frustration_explanation": r["frustration_explanation"],
            "tool_usage_label": r["tool_usage_label"],
            "tool_usage_explanation": r["tool_usage_explanation"],
        }
        for r in results
    ])

    try:
        from datetime import datetime as _dt
        versioned_name = f"{DATASET_NAME}-{_dt.now().strftime('%Y%m%d-%H%M%S')}"
        phoenix_client = px.Client(endpoint=PHOENIX_BASE_URL)
        phoenix_client.upload_dataset(
            dataframe=dataset_df,
            dataset_name=versioned_name,
            input_keys=["input"],
            output_keys=["output"],
            metadata_keys=["group", "expected_tool",
                           "frustration_label", "tool_usage_label"],
        )
        print(f"  Created Phoenix dataset '{versioned_name}' ✓")
        print("  View at http://localhost:6006 → Datasets & Experiments")

    except Exception as exc:
        print(f"  [warn] Dataset upload failed: {exc}")
        print("  Tip: Go to Phoenix UI → Datasets & Experiments → Import CSV")
        print(f"       and upload: evals/all_evaluations.csv")


# ---------------------------------------------------------------------------
# LLM judge
# ---------------------------------------------------------------------------
def run_judge(template: str, **kwargs) -> dict:
    """Run a single LLM-as-a-judge evaluation call.

    Args:
        template: Prompt template string with {placeholders}.
        **kwargs: Values to fill into the template.

    Returns:
        Dict with label, score, explanation, raw_response.
    """
    prompt = template.format(**kwargs)
    try:
        response = openai_client.chat.completions.create(
            model=JUDGE_MODEL,
            messages=[{"role": "user", "content": prompt}],
            temperature=0,  # Deterministic — same input → same label
            response_format={"type": "json_object"},
        )
        raw = response.choices[0].message.content
        result = json.loads(raw)
        result["raw_response"] = raw
        return result
    except Exception as exc:
        return {
            "label": "error",
            "score": None,
            "explanation": f"Judge call failed: {exc}",
            "raw_response": None,
        }


# ---------------------------------------------------------------------------
# Main evaluation pipeline
# ---------------------------------------------------------------------------
def main() -> None:
    # ── Load query results ────────────────────────────────────────────────
    if not QUERY_RESULTS_PATH.exists():
        print(f"ERROR: {QUERY_RESULTS_PATH} not found.")
        print("Run: poetry run python scripts/run_queries.py")
        return

    with open(QUERY_RESULTS_PATH) as f:
        queries = json.load(f)

    ok_queries = [q for q in queries if q["status"] == "ok"]

    print("=" * 65)
    print("  Travel Assistant — Evaluation Pipeline")
    print(f"  Judge model    : {JUDGE_MODEL}")
    print(f"  Queries        : {len(ok_queries)}")
    print(f"  Phoenix client : {'7.0.0' if _PHOENIX_AVAILABLE else 'unavailable'}")
    print("=" * 65)

    # ── Step 1: Export spans from Phoenix ─────────────────────────────────
    print("\n  Step 1 — Exporting traces from Phoenix...")
    spans_df = get_phoenix_spans()
    span_map = build_span_query_map(spans_df)
    print(f"  Matched {len(span_map)} root spans to queries\n")

    # ── Step 2: Run LLM-as-a-judge evaluations ────────────────────────────
    print("  Step 2 — Running LLM-as-a-judge evaluations...\n")
    results = []

    for i, q in enumerate(ok_queries, 1):
        print(f"[{i}/{len(ok_queries)}] Query #{q['id']} ({q['group']})")
        print(f"  Q: {q['message'][:70]}...")

        # Evaluation 1 — User Frustration
        frustration = run_judge(
            USER_FRUSTRATION_TEMPLATE,
            query=q["message"],
            response=q["response"],
        )
        print(f"  Frustration  : {frustration['label']:20s} — {frustration['explanation']}")

        # Evaluation 2 — Tool Usage Correctness
        tool_usage = run_judge(
            TOOL_USAGE_TEMPLATE,
            query=q["message"],
            expected_tool=q["expected_tool"],
            response=q["response"],
        )
        print(f"  Tool usage   : {tool_usage['label']:20s} — {tool_usage['explanation']}\n")

        # Match to Phoenix span (exact then fuzzy)
        span_key = q["message"][:100]
        span_id = span_map.get(span_key, "")
        if not span_id:
            prefix = q["message"][:60]
            for k, v in span_map.items():
                if prefix in k:
                    span_id = v
                    break

        results.append({
            **q,
            "span_id": span_id,
            "frustration_label": frustration["label"],
            "frustration_score": frustration.get("score"),
            "frustration_explanation": frustration["explanation"],
            "tool_usage_label": tool_usage["label"],
            "tool_usage_score": tool_usage.get("score"),
            "tool_usage_explanation": tool_usage["explanation"],
        })

        time.sleep(1)  # Avoid OpenAI rate limits

    # ── Summary ───────────────────────────────────────────────────────────
    frustrated = [r for r in results if r["frustration_label"] == "frustrated"]
    correct_tools = [r for r in results if r["tool_usage_label"] == "correct"]
    matched_spans = [r for r in results if r.get("span_id")]

    print("=" * 65)
    print("  RESULTS SUMMARY")
    print("=" * 65)
    print(f"  Total evaluated       : {len(results)}")
    print(f"  Frustrated            : {len(frustrated)}/{len(results)}")
    print(f"  Tool usage correct    : {len(correct_tools)}/{len(results)}")
    print(f"  Tool accuracy         : {len(correct_tools)/len(results):.0%}")
    print(f"  Spans matched         : {len(matched_spans)}/{len(results)}")

    print("\n  Frustrated interactions:")
    for r in frustrated:
        print(f"    #{r['id']} [{r['group']}] — {r['message'][:60]}...")

    # ── Step 3: Save outputs ──────────────────────────────────────────────
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_PATH, "w") as f:
        json.dump(results, f, indent=2)
    print(f"\n  Full results      → {OUTPUT_PATH}")

    if frustrated:
        pd.DataFrame(frustrated)[
            ["id", "group", "message", "response",
             "frustration_label", "frustration_explanation",
             "tool_usage_label", "tool_usage_explanation"]
        ].to_csv(FRUSTRATED_DATASET_PATH, index=False)
        print(f"  Frustrated dataset → {FRUSTRATED_DATASET_PATH}")

    pd.DataFrame(results).to_csv("evals/all_evaluations.csv", index=False)
    print("  All evaluations   → evals/all_evaluations.csv")

    # ── Step 4: Upload evaluations to Phoenix ─────────────────────────────
    print("\n  Step 3 — Uploading evaluation results to Phoenix...")
    log_evaluations_to_phoenix(results)

    # ── Step 5: Create Phoenix dataset ────────────────────────────────────
    print("\n  Step 4 — Creating Phoenix dataset...")
    create_phoenix_dataset(results)

    print(f"\n  View traces + evals at http://localhost:6006")
    print("=" * 65)


if __name__ == "__main__":
    main()
