"""
evaluate.py — Evaluation pipeline for the travel assistant.

Methodology:
  We use LLM-as-a-judge (GPT-4o-mini) to evaluate the quality of agent
  responses across two dimensions:

  1. User Frustration Detection
     Classifies each interaction as "frustrated" or "not frustrated".
     A frustrated interaction is one where the user's goal was not met —
     the agent couldn't book, gave vague answers, or failed to use the
     right tool.

  2. Tool Usage Correctness
     Classifies whether the agent invoked the appropriate tool(s):
       - Weather queries   → get_current_weather
       - General queries   → duckduckgo_search
       - Booking requests  → no tool (decline gracefully)

  Phoenix integration (client pinned to 7.0.0):

       1. Export traces from Phoenix as a DataFrame
            px.Client().get_spans_dataframe(project_name="travel-assistant")

       2. Run LLM-as-a-judge evaluations against the query/response pairs

       3. Upload evaluation results back to Phoenix
            px.log_evaluations(SpanEvaluations(...), project_name="travel-assistant")
            → Annotations appear in Phoenix Traces UI as evaluation columns

       4. Create a reusable evaluation dataset in Phoenix
            client.upload_dataset(...)
            → Visible under Datasets & Experiments

     We pin the Phoenix client to 7.0.0 because the phoenix.evals.models
     namespace — required by internal Phoenix imports — was split into a
     separate package in v8+, breaking the import.

  Data source:
     scripts/query_results.json — generated by run_queries.py.
     Contains all 10 query/response pairs with expected_tool metadata.

  Outputs:
     evals/evaluation_results.json   — full results for all 10 queries
     evals/frustrated_dataset.csv    — only the frustrated interactions
     evals/all_evaluations.csv       — all evaluations
     Phoenix Traces UI               — user_frustration + tool_usage_correctness columns
     Phoenix Datasets & Experiments  — travel-assistant-eval-v1 dataset

Usage:
    Make sure Phoenix is running: docker run -p 6006:6006 arizephoenix/phoenix:latest
    poetry run python evals/evaluate.py --with evals
"""

